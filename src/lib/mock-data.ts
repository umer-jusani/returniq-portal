function iso(offsetHours: number) {
  return new Date(Date.now() + offsetHours * 36e5).toISOString();
}

function day(offsetDays: number) {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().slice(0, 10);
}

